<p>條碼是一種將資料寫成機器可讀圖案的方式。這種圖案通常是寬度不同的黑白線條，或是排列在一個正方形中的許多小方塊。掃描時，圖案會被轉換回數字或文字，例如商品代碼、物流單號或網址。</p>
